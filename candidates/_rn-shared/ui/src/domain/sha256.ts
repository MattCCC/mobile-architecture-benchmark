// Pure-JS SHA-256 (FIPS 180-4) for the state and Insights digests. Hermes has no WebCrypto digest API,
// and the digest is computed only at checkpoints, outside measured windows (design §6.1 rule 5).
// Tested against node:crypto and the golden digests in fixtures/v1/golden.json.

